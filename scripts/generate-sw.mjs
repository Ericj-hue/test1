/**
 * Writes `dist/sw.js`, the service worker that makes the web build work offline.
 *
 *   npm run build:web     (runs `expo export -p web`, then this script)
 *
 * Every file of the build is cached when the app is first opened. The cache
 * name contains a hash of the build, so publishing a new build replaces the
 * old files automatically the next time the app is opened online.
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');

if (!existsSync(path.join(dist, 'index.html'))) {
  console.error('dist/index.html not found. Run "npx expo export -p web" first.');
  process.exit(1);
}

function walk(directory) {
  const files = [];
  for (const name of readdirSync(directory)) {
    const full = path.join(directory, name);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

const SKIP = [/^sw\.js$/, /\.map$/, /^metadata\.json$/, /^debug\.html$/];
const hash = createHash('sha256');
const assets = [];

for (const file of walk(dist).sort()) {
  const relative = path.relative(dist, file).split(path.sep).join('/');
  if (SKIP.some((pattern) => pattern.test(relative))) continue;
  hash.update(relative);
  hash.update(readFileSync(file));
  assets.push('/' + encodeURI(relative));
}

const version = hash.digest('hex').slice(0, 12);

const source = `// Generated by scripts/generate-sw.mjs - do not edit.
const CACHE = 'snooker-${version}';
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('snooker-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Every screen of the app is served by the same page.
  if (request.mode === 'navigate') {
    event.respondWith(caches.match('/index.html', { cacheName: CACHE }).then((cached) => cached || fetch(request)));
    return;
  }
  event.respondWith(
    caches.match(request, { cacheName: CACHE, ignoreSearch: true }).then((cached) => cached || fetch(request)),
  );
});
`;

writeFileSync(path.join(dist, 'sw.js'), source);
console.log(`Service worker written: dist/sw.js (${assets.length} files, version ${version})`);
